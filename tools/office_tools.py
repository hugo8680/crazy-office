def network_inspect(inp,args):
    raw=source(args.get('logs',inp.get('logs')))
    if isinstance(raw,dict):raw=raw.get('requests',raw.get('logs',raw.get('data')))
    if isinstance(raw,str):
        parsed=[]
        pattern=re.compile(r'^(\S+)\s+\S+\s+\S+\s+\[([^]]+)\]\s+"(\S+)\s+([^ ]+)\s+[^"]+"\s+(\d{3})')
        for n,l in enumerate(raw.splitlines(),1):
            if not l.strip():continue
            m=pattern.match(l)
            if not m:raise ValueError('无法解析第%d行access log，支持JSON/CSV或nginx combined格式'%n)
            ip,stamp,method,url,status=m.groups()
            try:stamp=datetime.strptime(stamp,'%d/%b/%Y:%H:%M:%S %z').isoformat()
            except ValueError:raise ValueError('日志时间格式错误')
            parsed.append({'ip':ip,'timestamp':stamp,'method':method,'path':url,'status':int(status)})
        raw=parsed
    if not isinstance(raw,list) or not raw:raise ValueError('请提供非空访问日志，不会自动生成事故')
    if len(raw)>100000:raise ValueError('单次最多100000条访问日志')
    import ipaddress
    rows=[]
    for i,r in enumerate(raw):
        if not isinstance(r,dict):raise ValueError('日志每条须为对象')
        try:ip=str(ipaddress.ip_address(r.get('ip',r.get('source_ip',''))))
        except ValueError:raise ValueError('第%d条IP无效'%(i+1))
        stamp=r.get('timestamp',r.get('time'))
        try:dt=datetime.fromisoformat(str(stamp).replace('Z','+00:00'))
        except Exception:raise ValueError('第%d条日志时间须为ISO 8601'%(i+1))
        if dt.tzinfo is None:raise ValueError('日志时间必须有时区')
        try:status=int(r.get('status',200))
        except Exception:raise ValueError('HTTP状态码无效')
        if not 100<=status<=599:raise ValueError('HTTP状态码应为100至599')
        label=str(r.get('label','unknown')).lower()
        if label not in ('normal','malicious','unknown'):raise ValueError('label只支持normal/malicious/unknown；未知不能伪造标签')
        rows.append({'id':i+1,'ip':ip,'timestamp':dt.isoformat(),'epoch':dt.timestamp(),'method':str(r.get('method','GET')).upper(),'path':str(r.get('path','/'))[:2048],'status':status,'label':label})
    rows.sort(key=lambda x:(x['epoch'],x['id']));save('network/requests.json',rows)
    with path('network/access.log').open('w') as f:
        for r in rows:f.write(json.dumps(r,ensure_ascii=False)+'\n')
    result={'requests':len(rows),'sources':len(set(r['ip'] for r in rows)),'windowStart':rows[0]['timestamp'],'windowEnd':rows[-1]['timestamp'],'windowSeconds':max(1,rows[-1]['epoch']-rows[0]['epoch']),'errorRequests':sum(r['status']>=500 for r in rows),'labels':{k:sum(r['label']==k for r in rows) for k in ['normal','malicious','unknown']},'environment':'本次任务隔离请求重放；不连接或改变生产网络'}
    save('network/inspection.json',result);return {'summary':'读取%d条真实输入日志，%d个来源'%(result['requests'],result['sources']),'evidence':result,'files':['network/requests.json','network/access.log','network/inspection.json']}

def network_analyze(inp,args):
    rows=read('network/requests.json');threshold=int(args.get('threshold',inp.get('threshold',20)));window=int(args.get('windowSeconds',60))
    if not 1<=threshold<=100000 or not 1<=window<=3600:raise ValueError('阈值或时间窗超出范围')
    by={}
    for r in rows:by.setdefault(r['ip'],[]).append(r)
    sources=[]
    for ip,rr in by.items():
        peak=0;start=0
        for end,r in enumerate(rr):
            while rr[start]['epoch']<=r['epoch']-window:start+=1
            peak=max(peak,end-start+1)
        paths={p:sum(r['path']==p for r in rr) for p in set(r['path'] for r in rr)}
        sources.append({'ip':ip,'requests':len(rr),'peakRequestsPerWindow':peak,'windowSeconds':window,'threshold':threshold,'overThreshold':peak>threshold,'errorRequests':sum(r['status']>=500 for r in rr),'methods':sorted(set(r['method'] for r in rr)),'topPaths':sorted(paths.items(),key=lambda x:-x[1])[:5],'evidenceSample':[{k:r[k] for k in ['timestamp','path','status']} for r in rr[:3]]})
    sources.sort(key=lambda x:-x['peakRequestsPerWindow'])
    result={'threshold':threshold,'windowSeconds':window,'sources':sources,'suspectedSources':[r['ip'] for r in sources if r['overThreshold']],'limitations':['高频来源只是异常证据，可能包含NAT共享出口；不能凭请求量认定攻击。','IP规则只对输入日志和本次重放有效；真实DDoS需要上游清洗及生产监控。'],'recommendation':'由安全Agent依据请求证据决定blockedIps或rateLimit；变更必须经真人批准'}
    save('network/analysis.json',result);return {'summary':'完成来源聚合和滑动时间窗分析，%d个来源超阈值'%len(result['suspectedSources']),'evidence':result,'files':['network/analysis.json']}

def network_verify(inp,args):
    rows=read('network/requests.json');policy=read('network/defense.json') if path('network/defense.json').exists() else {'approved':False,'blockedIps':[],'rateLimit':None,'windowSeconds':60}
    blocked=set(policy.get('blockedIps',[])) if policy.get('approved') else set();limit=policy.get('rateLimit') if policy.get('approved') else None;window=policy.get('windowSeconds',60);history={};results=[]
    for r in rows:
        hh=history.setdefault(r['ip'],[])
        while hh and hh[0]<=r['epoch']-window:hh.pop(0)
        limited=limit is not None and len(hh)>=limit
        accepted=r['ip'] not in blocked and not limited
        hh.append(r['epoch'])
        results.append({'id':r['id'],'ip':r['ip'],'path':r['path'],'label':r['label'],'accepted':accepted,'reason':'IP规则拒绝' if r['ip'] in blocked else '速率规则拒绝' if limited else '允许','originalStatus':r['status']})
    normal=[r for r in results if r['label']=='normal'];bad=[r for r in results if r['label']=='malicious'];unknown=[r for r in results if r['label']=='unknown']
    normalpass=sum(r['accepted'] for r in normal);badblock=sum(not r['accepted'] for r in bad)
    result={'approved':bool(policy.get('approved')),'totalRequests':len(rows),'accepted':sum(r['accepted'] for r in results),'blocked':sum(not r['accepted'] for r in results),'normalRequests':len(normal),'normalPassed':normalpass,'normalPassRate':round(normalpass/len(normal),6) if normal else None,'falsePositives':len(normal)-normalpass,'maliciousRequests':len(bad),'maliciousBlocked':badblock,'maliciousBlockRate':round(badblock/len(bad),6) if bad else None,'unknownLabelRequests':len(unknown),'verifiedRestored':bool(policy.get('approved')) and bool(normal) and bool(bad) and not unknown and normalpass==len(normal) and badblock==len(bad),'limitations':['这是实际输入日志在隔离策略解释器中的重放，不代表HTTP服务器响应恢复或生产网络恢复。','normal/malicious为输入数据的验收标签，工具不会自行生成真值。']}
    save('network/replay.json',results);save('network/verification.json',result)
    csv_write('network/replay.csv',['id','ip','path','label','accepted','reason','originalStatus'],[[r[k] for k in ['id','ip','path','label','accepted','reason','originalStatus']] for r in results])
    return {'summary':'隔离重放验证完成；'+('符合本次带标签日志验收条件' if result['verifiedRestored'] else '尚不能确认恢复，查看误伤/漏拦或标签缺失'),'evidence':result,'files':['network/replay.json','network/replay.csv','network/verification.json']}


