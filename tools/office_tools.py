def cents(v,field,row):
    try: d=Decimal(str(v).replace(',','').strip())
    except (InvalidOperation,ValueError): raise ValueError('第%d行%s不是有效金额'%(row,field))
    if not d.is_finite(): raise ValueError('金额不能为NaN或无穷大')
    if d!=d.quantize(Decimal('0.01')): raise ValueError('金额最多保留两位小数: '+field)
    if abs(d)>Decimal('1000000000000'): raise ValueError('金额超出工具支持范围')
    if d<0 and field!='other_income': raise ValueError('非负金额字段出现负值: '+field)
    return int(d*100)

