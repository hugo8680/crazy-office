# Database tools: allowlisted statements and SQLite authorizer provide layered confinement.
def statements(sql):
    if not isinstance(sql,str) or len(sql)>150000: raise ValueError('SQL必须为文本且不超过150KB')
    out=[]; buf=''
    for ch in sql:
        buf+=ch
        if ch==';' and sqlite3.complete_statement(buf): out.append(buf.strip());buf=''
    if buf.strip(): out.append(buf.strip())
    return out

def token_statement(s): return re.sub(r'(?s)/\*.*?\*/|--[^\n]*',' ',s).strip()

def safe_sql(sql,mode):
    ss=statements(sql)
    if not ss: raise ValueError('SQL为空')
    allowed={'design':r'^CREATE\s+(?:TABLE|(?:UNIQUE\s+)?INDEX)\b','insert':r'^INSERT\s+INTO\b','select':r'^(?:SELECT|WITH)\b','test':r'^(?:INSERT\s+INTO|UPDATE\b|DELETE\s+FROM|SELECT\b|WITH\b)'}[mode]
    for s in ss:
        t=token_statement(s)
        if not re.match(allowed,t,re.I): raise ValueError('本操作不允许此SQL语句: '+t[:70])
        if re.search(r'\b(?:ATTACH|DETACH|PRAGMA|VACUUM|LOAD_EXTENSION|WRITABLE_SCHEMA|VIRTUAL\s+TABLE)\b',t,re.I): raise ValueError('禁止跨文件访问、扩展、虚拟表及PRAGMA')
    return ss

def authorizer(action,p1,p2,db,source):
    banned=[sqlite3.SQLITE_ATTACH,sqlite3.SQLITE_DETACH]
    if action in banned: return sqlite3.SQLITE_DENY
    if action==sqlite3.SQLITE_FUNCTION and str(p2 or p1).lower() in ('load_extension','readfile','writefile','randomblob','zeroblob'): return sqlite3.SQLITE_DENY
    return sqlite3.SQLITE_OK

