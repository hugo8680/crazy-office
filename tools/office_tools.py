ROOT = None

def path(name):
    p=(ROOT/name).resolve()
    if ROOT not in p.parents: raise ValueError('文件必须位于本次任务工作区')
    p.parent.mkdir(parents=True,exist_ok=True)
    return p

def save(name,obj):
    path(name).write_text(json.dumps(obj,ensure_ascii=False,indent=2),encoding='utf8'); return name

def read(name): return json.loads(path(name).read_text(encoding='utf8'))

def source(v):
    if isinstance(v,dict) and ('base64' in v or 'text' in v):
        name=str(v.get('name','input.json'))
        if 'base64' in v:
            try: raw=base64.b64decode(v['base64'],validate=True)
            except Exception: raise ValueError('文件base64编码无效')
        else: raw=str(v['text']).encode('utf8')
        if len(raw)>10*1024*1024: raise ValueError('文件超过10MB')
        if name.lower().endswith('.xlsx'): return xlsx_rows(raw)
        try: text=raw.decode('utf-8-sig')
        except UnicodeError: raise ValueError('文本须采用UTF-8编码')
        if name.lower().endswith('.json'):
            try: return json.loads(text)
            except Exception: raise ValueError('JSON文件格式错误')
        if name.lower().endswith(('.csv','.tsv')):
            return list(csv.DictReader(io.StringIO(text),delimiter='\t' if name.endswith('.tsv') else ','))
        return text
    if isinstance(v,str):
        s=v.strip()
        if s.startswith(('[','{')):
            try: return json.loads(s)
            except Exception: raise ValueError('JSON文本格式错误')
        if '\n' in s and ',' in s.splitlines()[0]: return list(csv.DictReader(io.StringIO(s)))
        return v
    return v

def xlsx_rows(raw):
    try:
        z=zipfile.ZipFile(io.BytesIO(raw))
        if len(z.infolist())>300 or sum(i.file_size for i in z.infolist())>30*1024*1024: raise ValueError('XLSX压缩内容过大')
        ns={'m':'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
        strings=[]
        if 'xl/sharedStrings.xml' in z.namelist():
            strings=[''.join(n.itertext()) for n in ET.fromstring(z.read('xl/sharedStrings.xml')).findall('m:si',ns)]
        # Resolve first workbook sheet, supporting files generated by Excel/openpyxl.
        wb=ET.fromstring(z.read('xl/workbook.xml')); sheets=wb.find('m:sheets',ns)
        if sheets is None or not len(sheets): raise ValueError('XLSX没有工作表')
        rid=sheets[0].get('{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id')
        rels=ET.fromstring(z.read('xl/_rels/workbook.xml.rels'))
        target=next((r.get('Target') for r in rels if r.get('Id')==rid),None)
        if not target: raise ValueError('XLSX工作表关系无效')
        sheet=('xl/'+target.lstrip('/')) if not target.startswith('/') else target.lstrip('/')
        sheet=sheet.replace('xl/xl/','xl/')
        rows=[]
        for row in ET.fromstring(z.read(sheet)).findall('.//m:sheetData/m:row',ns):
            vals={}
            for c in row.findall('m:c',ns):
                ref=c.get('r','A1'); letters=re.match(r'[A-Z]+',ref).group(); idx=0
                for l in letters: idx=idx*26+ord(l)-64
                if c.find('m:f',ns) is not None: raise ValueError('不接受公式财务输入；请导出已核实的数值，避免缓存值过期')
                typ=c.get('t'); v=c.find('m:v',ns)
                if typ=='s': value=strings[int(v.text)] if v is not None else ''
                elif typ=='inlineStr': value=''.join(c.find('m:is',ns).itertext())
                else: value=v.text if v is not None else ''
                vals[idx-1]=value
            rows.append([vals.get(i,'') for i in range(max(vals.keys(),default=-1)+1)])
        if not rows: raise ValueError('XLSX为空')
        headers=[str(x).strip() for x in rows[0]]
        if len(set(headers))!=len(headers): raise ValueError('XLSX存在重复列名')
        return [dict(zip(headers,r+['']*(len(headers)-len(r)))) for r in rows[1:] if any(str(x).strip() for x in r)]
    except (zipfile.BadZipFile, KeyError,ET.ParseError) as e: raise ValueError('无法解析XLSX文件: '+str(e))

def csv_write(name,headers,rows):
    with path(name).open('w',encoding='utf-8-sig',newline='') as f:
        w=csv.writer(f); w.writerow(headers); w.writerows(rows)
    return name

def xlsx_write(name,sheets):
    esc=lambda x: html.escape(str(x),quote=True)
    def col(n):
        s=''
        while n: n,r=divmod(n-1,26); s=chr(65+r)+s
        return s
    with zipfile.ZipFile(path(name),'w',zipfile.ZIP_DEFLATED) as z:
        z.writestr('[Content_Types].xml','<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'+''.join('<Override PartName="/xl/worksheets/sheet%d.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'%(i+1) for i in range(len(sheets)))+'</Types>')
        z.writestr('_rels/.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>')
        z.writestr('xl/workbook.xml','<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>'+''.join('<sheet name="%s" sheetId="%d" r:id="rId%d"/>'%(esc(title),i+1,i+1) for i,(title,_) in enumerate(sheets))+'</sheets></workbook>')
        z.writestr('xl/_rels/workbook.xml.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'+''.join('<Relationship Id="rId%d" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet%d.xml"/>'%(i+1,i+1) for i in range(len(sheets)))+'</Relationships>')
        for i,(_,rows) in enumerate(sheets):
            xml=[]
            for rn,row in enumerate(rows,1):
                cells=[]
                for cn,value in enumerate(row,1):
                    ref='%s%d'%(col(cn),rn)
                    if isinstance(value,(int,float,Decimal)) and not isinstance(value,bool): cells.append('<c r="%s"><v>%s</v></c>'%(ref,value))
                    else: cells.append('<c r="%s" t="inlineStr"><is><t xml:space="preserve">%s</t></is></c>'%(ref,esc('' if value is None else value)))
                xml.append('<row r="%d">%s</row>'%(rn,''.join(cells)))
            z.writestr('xl/worksheets/sheet%d.xml'%(i+1),'<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" state="frozen"/></sheetView></sheetViews><cols><col min="1" max="20" width="22" customWidth="1"/></cols><sheetData>'+''.join(xml)+'</sheetData></worksheet>')
    return name

